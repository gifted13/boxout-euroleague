// never translated — it's data, not UI copy. Stat abbreviations shown in
// tight table headers (PTS, AST, REB, PPG, ORTG…) also stay as-is in both
// languages — they're the same shorthand EuroLeague broadcasts use
// regardless of language, and translating them would make columns wider
// than the tables are built for. Full stat names/descriptions (used in the
// ⓘ tooltips and percentile rows) ARE translated — see STAT_META in
// format.js. Everything else a person reads as app chrome — nav, headers,
// buttons, empty states, insight-card sentences — is translated here.
// ============================================================================

